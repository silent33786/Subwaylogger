"""
Firefox Profile Storage Engine.
Manages physical Firefox profile directories, filesystem isolation,
user.js preferences generation, session persistence files, and lock detection.
"""

import json
import os
import shutil
from pathlib import Path
from typing import Optional, Dict, Any

from firefox_manager.config.settings import settings


class ProfileStorageManager:
    """Manages physical profile folders and config files on disk."""

    def __init__(self, profiles_base_dir: Optional[Path] = None):
        self.base_dir = Path(profiles_base_dir or settings.profiles_dir).resolve()
        self.base_dir.mkdir(parents=True, exist_ok=True)

    def get_profile_path(self, directory_name: str) -> Path:
        """Resolve absolute path to a profile directory."""
        return (self.base_dir / directory_name).resolve()

    def profile_exists(self, directory_name: str) -> bool:
        """Check if profile directory exists on disk."""
        return self.get_profile_path(directory_name).is_dir()

    def create_profile_directory(
        self,
        directory_name: str,
        profile_id: str,
        profile_name: str,
        custom_user_agent: Optional[str] = None,
        proxy_server: Optional[str] = None,
        extra_prefs: Optional[Dict[str, Any]] = None,
    ) -> Path:
        """
        Create a new isolated Firefox profile directory with persistent configuration.
        Initializes user.js with isolation preferences.
        """
        profile_path = self.get_profile_path(directory_name)
        if profile_path.exists():
            raise FileExistsError(
                f"Profile directory '{directory_name}' already exists at {profile_path}"
            )

        profile_path.mkdir(parents=True, exist_ok=False)

        # Write metadata file for audit & ownership verification
        meta_file = profile_path / "profile_meta.json"
        meta_data = {
            "profile_id": profile_id,
            "profile_name": profile_name,
            "directory_name": directory_name,
            "created_by": "FirefoxMultiProfileManager",
            "version": "1.0",
        }
        meta_file.write_text(json.dumps(meta_data, indent=2), encoding="utf-8")

        # Generate custom user.js preferences
        self.apply_preferences(
            directory_name=directory_name,
            custom_user_agent=custom_user_agent,
            proxy_server=proxy_server,
            extra_prefs=extra_prefs,
        )

        return profile_path

    def apply_preferences(
        self,
        directory_name: str,
        custom_user_agent: Optional[str] = None,
        proxy_server: Optional[str] = None,
        extra_prefs: Optional[Dict[str, Any]] = None,
    ) -> None:
        """Write user.js inside the profile directory to lock in desired settings."""
        profile_path = self.get_profile_path(directory_name)
        if not profile_path.is_dir():
            raise FileNotFoundError(f"Profile directory not found: {profile_path}")

        user_prefs = dict(settings.default_prefs)

        if custom_user_agent:
            user_prefs["general.useragent.override"] = custom_user_agent

        if proxy_server:
            # Parse proxy format host:port or http://host:port or socks5://host:port
            self._configure_proxy_prefs(user_prefs, proxy_server)

        if extra_prefs:
            user_prefs.update(extra_prefs)

        user_js_file = profile_path / "user.js"
        lines = [
            "// Auto-generated by Firefox Multi-Profile Manager",
            "// Enterprise persistent profile configuration",
        ]
        for key, val in user_prefs.items():
            if isinstance(val, bool):
                val_str = "true" if val else "false"
            elif isinstance(val, (int, float)):
                val_str = str(val)
            elif isinstance(val, str):
                escaped_val = val.replace('"', '\\"')
                val_str = f'"{escaped_val}"'
            else:
                continue
            lines.append(f'user_pref("{key}", {val_str});')

        user_js_file.write_text("\n".join(lines) + "\n", encoding="utf-8")

    def _configure_proxy_prefs(self, prefs: dict, proxy_str: str) -> None:
        """Configure Firefox manual proxy preferences."""
        clean = proxy_str.replace("http://", "").replace("https://", "").replace("socks5://", "")
        parts = clean.split(":")
        if len(parts) == 2:
            host, port_str = parts[0], parts[1]
            try:
                port = int(port_str)
                prefs["network.proxy.type"] = 1  # Manual proxy configuration
                if "socks5://" in proxy_str:
                    prefs["network.proxy.socks"] = host
                    prefs["network.proxy.socks_port"] = port
                    prefs["network.proxy.socks_version"] = 5
                else:
                    prefs["network.proxy.http"] = host
                    prefs["network.proxy.http_port"] = port
                    prefs["network.proxy.ssl"] = host
                    prefs["network.proxy.ssl_port"] = port
            except ValueError:
                pass

    def is_profile_locked(self, directory_name: str) -> bool:
        """
        Check if the profile directory is currently locked by a running Firefox instance.
        On Windows, Firefox places an exclusive lock on 'parent.lock'.
        """
        profile_path = self.get_profile_path(directory_name)
        lock_file = profile_path / "parent.lock"
        if not lock_file.exists():
            return False

        # Try to open lock_file in append/write mode to check for exclusive OS lock
        try:
            with open(lock_file, "r+b"):
                # If we could open it, Firefox is not actively locking it
                return False
        except (IOError, PermissionError):
            # File is held by another process
            return True

    def remove_stale_lock(self, directory_name: str) -> bool:
        """Remove orphaned parent.lock file if process is definitely terminated."""
        profile_path = self.get_profile_path(directory_name)
        lock_file = profile_path / "parent.lock"
        if not lock_file.exists():
            return True

        try:
            lock_file.unlink(missing_ok=True)
            return True
        except (IOError, PermissionError):
            return False

    def calculate_disk_usage(self, directory_name: str) -> int:
        """Return total bytes occupied by profile directory."""
        profile_path = self.get_profile_path(directory_name)
        if not profile_path.is_dir():
            return 0
        total = 0
        for root, _, files in os.walk(profile_path):
            for f in files:
                fp = os.path.join(root, f)
                try:
                    total += os.path.getsize(fp)
                except (OSError, FileNotFoundError):
                    pass
        return total

    def has_session_data(self, directory_name: str) -> bool:
        """Check if profile has existing persistent cookie/session data."""
        profile_path = self.get_profile_path(directory_name)
        cookies_db = profile_path / "cookies.sqlite"
        session_store = profile_path / "sessionstore-backups"
        return (cookies_db.exists() and cookies_db.stat().st_size > 0) or session_store.exists()

    def delete_profile_directory(self, directory_name: str, max_retries: int = 8) -> bool:
        """
        Permanently delete profile folder from the system disk.
        Aggressively strips read-only attributes, terminates residual locks,
        and uses PowerShell & cmd force-removal to ensure zero junk files remain.
        """
        import stat
        import subprocess
        import time

        profile_path = self.get_profile_path(directory_name)
        if not profile_path.exists():
            return True

        def _clear_readonly(func, path, exc_info):
            try:
                os.chmod(path, stat.S_IWRITE)
                func(path)
            except Exception:
                pass

        for attempt in range(max_retries):
            # 1. Strip read-only attributes recursively
            for root, dirs, files in os.walk(profile_path):
                for d in dirs:
                    try:
                        os.chmod(os.path.join(root, d), stat.S_IWRITE)
                    except OSError:
                        pass
                for f in files:
                    try:
                        os.chmod(os.path.join(root, f), stat.S_IWRITE)
                    except OSError:
                        pass

            # 2. Try shutil.rmtree
            try:
                shutil.rmtree(profile_path, onerror=_clear_readonly)
                if not profile_path.exists():
                    return True
            except Exception:
                pass

            # 3. Windows cmd force removal
            if os.name == "nt":
                try:
                    subprocess.run(
                        f'cmd.exe /c rd /s /q "{profile_path}"',
                        shell=True,
                        capture_output=True,
                        timeout=5,
                    )
                except Exception:
                    pass

                if not profile_path.exists():
                    return True

                # 4. PowerShell Force Removal
                try:
                    subprocess.run(
                        ["powershell", "-NoProfile", "-Command", f'Remove-Item -LiteralPath "{profile_path}" -Recurse -Force -ErrorAction SilentlyContinue'],
                        capture_output=True,
                        timeout=5,
                    )
                except Exception:
                    pass

                if not profile_path.exists():
                    return True

            time.sleep(0.6)

        return not profile_path.exists()


# Global storage manager instance
profile_storage = ProfileStorageManager()

